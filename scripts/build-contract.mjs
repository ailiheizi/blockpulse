import { execFileSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

// Requires a local Foundry install with solc 0.8.30 cached; forge runs offline.
const root = new URL('../', import.meta.url);
const contracts = fileURLToPath(new URL('contracts/', root));
execFileSync('forge', ['build'], { cwd: contracts, stdio: 'inherit' });
const artifact = JSON.parse(await readFile(new URL('contracts/out/BlockPulseMarket.sol/BlockPulseMarket.json', root), 'utf8'));
const cast = args => execFileSync('cast', args, { encoding: 'utf8' }).trim();
const signature = item => `${item.name}(${item.inputs.map(input => input.type).join(',')})`;

const functions = {};
for (const [sig, id] of Object.entries(artifact.methodIdentifiers)) {
  const name = sig.slice(0, sig.indexOf('('));
  if (functions[name]) throw new Error(`Overloaded function is not supported: ${name}`);
  functions[name] = `0x${id}`;
}
const errors = Object.fromEntries(artifact.abi.filter(item => item.type === 'error')
  .map(item => [cast(['sig', signature(item)]), item.name]));
const events = Object.fromEntries(artifact.abi.filter(item => item.type === 'event')
  .map(item => [item.name, cast(['keccak', signature(item)])]));

const output = {
  bytecode: artifact.bytecode.object,
  runtime: artifact.deployedBytecode.object,
  functions,
  errors,
  events,
};
const source = `// Generated by scripts/build-contract.mjs from contracts/src/BlockPulseMarket.sol. Do not edit.
export const MARKET_ARTIFACT = Object.freeze(${JSON.stringify(output, null, 2)});
`;
await writeFile(new URL('dist/monad-market-artifact.js', root), source, 'utf8');
console.log(`Wrote dist/monad-market-artifact.js (${(output.runtime.length - 2) / 2} bytes runtime).`);
